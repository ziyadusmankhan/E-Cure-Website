import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { loadEnvConfig } from "@next/env";
import postgres from "postgres";
import { startLocalPostgres, stopLocalPostgres } from "./local-postgres";
import { openDatabase } from "../src/server/db/connection";
import { migrateDatabase } from "../src/server/db/migrate";
import { safeError } from "../src/server/errors";

loadEnvConfig(process.cwd());
async function main() {
  const action = process.argv[2];
  if (!["start", "stop", "migrate"].includes(action))
    throw new Error("Unsupported local database action.");
  if (action === "stop") {
    stopLocalPostgres("development");
    console.log("Workspace development database stopped. Data retained.");
    return;
  }
  const local = startLocalPostgres("development");
  const maintenance = postgres(local.url, { max: 1, onnotice: () => {} });
  const dbUrl = new URL(local.url);
  dbUrl.pathname = "/healthcare_development";
  let connection: ReturnType<typeof openDatabase> | undefined;
  try {
    const [existing] =
      await maintenance`select 1 from pg_database where datname = 'healthcare_development'`;
    if (!existing) await maintenance`create database healthcare_development`;
    connection = openDatabase(dbUrl.toString(), "migration");
    await migrateDatabase(connection.db);
    await maintenance.unsafe(
      `ALTER ROLE healthcare_app LOGIN PASSWORD '${local.applicationPassword}'`,
    );
    dbUrl.username = "healthcare_app";
    dbUrl.password = local.applicationPassword;
    const runtimeUrl = dbUrl.toString();
    // Separate migration secrets stay outside the Next.js runtime environment.
    writeFileSync(join(local.root, "runtime.env"), `DATABASE_URL=${runtimeUrl}\n`, { mode: 0o600 });
    if (!existsSync(".env.local")) {
      writeFileSync(
        ".env.local",
        `# Local development only; generated by db:local:start. Never commit.\nDATABASE_URL=${runtimeUrl}\n`,
        { mode: 0o600, flag: "wx" },
      );
      console.log("Created ignored .env.local with the restricted runtime connection only.");
    } else if (!readFileSync(".env.local", "utf8").includes(runtimeUrl)) {
      console.log(
        "Existing .env.local preserved. The generated runtime connection is in .local/postgres-dev/runtime.env.",
      );
    }
    const check = openDatabase(runtimeUrl);
    try {
      await check.client`select id from healthcare.business_settings limit 1`;
    } finally {
      await check.close();
    }
    console.log(
      "Development PostgreSQL is ready on 127.0.0.1:55433; healthcare_development migrated and runtime access verified.",
    );
    console.log(
      "Use db:local:migrate for later local migrations. No customer, appointment or staff account has been seeded.",
    );
  } finally {
    await connection?.close();
    await maintenance.end({ timeout: 5 });
  }
}
main().catch((error) => {
  const safe = safeError(error);
  console.error(`${safe.code}: ${safe.message} Check PG_BIN and .local/postgres-dev/postgres.log.`);
  process.exitCode = 1;
});
